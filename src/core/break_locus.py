def pair_projection(word: tuple[str, ...], left: str, right: str) -> tuple[str, ...]:
    """Return the subsequence of the two letters (the pairwise projection)."""
    logger.debug("locus.pair_projection entry %s/%s", left, right)
    result = tuple(letter for letter in word if letter == left or letter == right)
    logger.debug("locus.pair_projection exit length=%d", len(result))
    return result


def delta_pairs(word: tuple[str, ...], other: tuple[str, ...], alphabet: tuple[str, ...]) -> tuple[Pair, ...] | None:
    """Return the pairs whose projections differ, or None on multiset mismatch."""
    logger.debug("locus.delta_pairs entry")
    if sorted(word) != sorted(other):
        logger.debug("locus.delta_pairs exit multiset-mismatch")
        return None
    result = tuple(
        (left, right)
        for left, right in combinations(sorted(alphabet), 2)
        if pair_projection(word, left, right) != pair_projection(other, left, right)
    )
    logger.debug("locus.delta_pairs exit count=%d", len(result))
    return result


def _valid_exponents(counts: tuple[int, ...]) -> tuple[int, ...]:
    logger.debug("locus._valid_exponents entry counts=%r", counts)
    total = sum(counts)
    result = tuple(
        k for k in range(2, total + 1)
        if all(count % k == 0 for count in counts)
    )
    logger.debug("locus._valid_exponents exit result=%r", result)
    return result


def power_candidates(word: tuple[str, ...], alphabet: tuple[str, ...]) -> tuple[PowerCandidateRow, ...]:
    """Enumerate all same-multiset powers v = u^k with their delta sets."""
    logger.debug("locus.power_candidates entry word=%s", "".join(word))
    letters = tuple(sorted(alphabet))
    counts = tuple(word.count(letter) for letter in letters)
    rows: list[PowerCandidateRow] = []
    seen_powers: set[tuple[str, ...]] = set()
    for exponent in _valid_exponents(counts):
        reduced: list[str] = []
        for letter, count in zip(letters, counts):
            reduced.extend([letter] * (count // exponent))
        for root in set(permutations(reduced)):
            power = root * exponent
            if power in seen_powers:
                continue
            seen_powers.add(power)
            delta = delta_pairs(word, power, letters)
            if delta is None:
                logger.error("locus.power_candidates impossible multiset drift")
                continue
            rows.append(PowerCandidateRow("".join(power), "".join(root), exponent, delta))
    result = tuple(sorted(rows, key=lambda row: (len(row.delta), row.power_word)))
    logger.debug("locus.power_candidates exit count=%d", len(result))
    return result


def _minimal_antichain(deltas: tuple[tuple[Pair, ...], ...]) -> tuple[tuple[Pair, ...], ...]:
    logger.debug("locus._minimal_antichain entry count=%d", len(deltas))
    unique = sorted(set(deltas), key=lambda item: (len(item), item))
    minimal: list[tuple[Pair, ...]] = []
    for candidate in unique:
        candidate_set = set(candidate)
        if not any(set(kept) <= candidate_set for kept in minimal):
            minimal.append(candidate)
    result = tuple(minimal)
    logger.debug("locus._minimal_antichain exit count=%d", len(result))
    return result


def break_locus(word: tuple[str, ...], alphabet: tuple[str, ...]) -> BreakLocus:
    """Compute the break locus of a word over the given alphabet."""
    logger.debug("locus.break_locus entry word=%s", "".join(word))
    text = "".join(word)
    letters = tuple(sorted(alphabet))
    if not word or any(letter not in letters for letter in word):
        result = BreakLocus(text, letters, (), (), True, False, False, "blocked", "foreign-or-empty-word")
        logger.error("locus.break_locus blocked foreign-or-empty")
        return result
    candidates = power_candidates(word, letters)
    if not candidates:
        result = BreakLocus(text, letters, (), (), True, False, True, "witnessed", "none")
        logger.debug("locus.break_locus exit absolutely-primitive")
        return result
    minimal = _minimal_antichain(tuple(row.delta for row in candidates))
    literal = minimal == ((),)
    result = BreakLocus(
        text, letters, candidates, minimal,
        len(minimal) <= 1, literal, False, "witnessed", "none",
    )
    logger.debug(
        "locus.break_locus exit minimal=%d principal=%s literal=%s",
        len(minimal), result.principal, literal,
    )
    return result


def predicted_break(locus: BreakLocus, node: CommutationDoctrine) -> tuple[bool, str]:
    """Return the Δ-prediction for one doctrine with its witnessing power."""
    logger.debug("locus.predicted_break entry node=%s", node.doctrine_id)
    independent = set(node.independent_pairs)
    for row in locus.candidates:
        if set(row.delta) <= independent:
            logger.debug("locus.predicted_break exit break witness=%s", row.power_word)
            return (True, row.power_word)
    logger.debug("locus.predicted_break exit no-break")
    return (False, "")


def cross_check_full_lattice(word: tuple[str, ...], alphabet: tuple[str, ...], cap: int = DEFAULT_CLASS_CAP) -> CrossCheckReport:
    """Verify Δ-predictions against BFS truth on every doctrine of the lattice."""
    logger.debug("locus.cross_check_full_lattice entry word=%s", "".join(word))
    text = "".join(word)
    letters = tuple(sorted(alphabet))
    locus = break_locus(word, letters)
    if locus.status != "witnessed":
        result = CrossCheckReport(text, 0, 0, (), "blocked", locus.obstruction)
        logger.error("locus.cross_check blocked %s", locus.obstruction)
        return result
    all_pairs = tuple(combinations(letters, 2))
    checked = refused = 0
    mismatches: list[str] = []
    for size in range(len(all_pairs) + 1):
        for chosen in combinations(all_pairs, size):
            node = doctrine("x".join("".join(pair) for pair in chosen) or "word", letters, chosen)
            if not isinstance(node, CommutationDoctrine):
                mismatches.append("doctrine-build:%r" % (chosen,))
                continue
            prediction, _witness = predicted_break(locus, node)
            row = primitivity_row(node, word, cap)
            if row.status == "refused":
                refused += 1
                continue
            checked += 1
            truth = not row.primitive
            if truth != prediction:
                mismatches.append("%s:predicted=%s:bfs=%s" % (node.doctrine_id, prediction, truth))
    status = "witnessed" if not mismatches else "blocked"
    result = CrossCheckReport(
        text, checked, refused, tuple(mismatches), status,
        "none" if not mismatches else "delta-bfs-mismatch",
    )
    if mismatches:
        logger.error("locus.cross_check mismatches=%d", len(mismatches))
    logger.debug("locus.cross_check exit checked=%d refused=%d", checked, refused)
    return result


def nonprincipal_sweep(alphabet: tuple[str, ...], counts: tuple[int, ...], word_cap: int = DEFAULT_SWEEP_CAP) -> SweepReport:
    """Exhaustively scan one multiset shape for non-principal break loci."""
    logger.debug("locus.nonprincipal_sweep entry alphabet=%r counts=%r", alphabet, counts)
    letters = tuple(sorted(alphabet))
    shape_id = "-".join("%s%d" % (letter, count) for letter, count in zip(letters, counts))
    if len(letters) != len(counts) or any(count < 1 for count in counts):
        result = SweepReport(shape_id, 0, 0, 0, 0, (), 0, "blocked", "invalid-shape")
        logger.error("locus.nonprincipal_sweep blocked invalid-shape")
        return result
    pool: list[str] = []
    for letter, count in zip(letters, counts):
        pool.extend([letter] * count)
    words = set(permutations(pool))
    if len(words) > word_cap:
        result = SweepReport(shape_id, 0, 0, 0, 0, (), 0, "refused", "sweep-size-refusal")
        logger.error("locus.nonprincipal_sweep refused size=%d", len(words))
        return result
    literal = absolute = principal_count = 0
    nonprincipal: list[str] = []
    max_size = 0
    for word in sorted(words):
        locus = break_locus(word, letters)
        if locus.status != "witnessed":
            result = SweepReport(shape_id, 0, 0, 0, 0, (), 0, "blocked", locus.obstruction)
            logger.error("locus.nonprincipal_sweep blocked %s", locus.obstruction)
            return result
        size = len(locus.minimal_deltas)
        max_size = size if size > max_size else max_size
        if locus.literal_power:
            literal += 1
        elif locus.absolutely_primitive:
            absolute += 1
        elif locus.principal:
            principal_count += 1
        else:
            nonprincipal.append(locus.word)
    result = SweepReport(
        shape_id, len(words), literal, absolute, principal_count,
        tuple(nonprincipal), max_size, "witnessed", "none",
    )
    logger.debug(
        "locus.nonprincipal_sweep exit scanned=%d nonprincipal=%d max=%d",
        len(words), len(nonprincipal), max_size,
    )
    return result


