logger = logging.getLogger(__name__)

DEFAULT_SWEEP_CAP = 20000
DEFAULT_CLASS_CAP = 1500

Pair = tuple[str, str]


@dataclass(frozen=True)
class PowerCandidateRow:
    """One same-multiset power candidate with its projection delta."""

    power_word: str
    root_word: str
    exponent: int
    delta: tuple[Pair, ...]


@dataclass(frozen=True)
class BreakLocus:
    """The minimal antichain of breaking pair-sets for one word."""

    word: str
    alphabet: tuple[str, ...]
    candidates: tuple[PowerCandidateRow, ...]
    minimal_deltas: tuple[tuple[Pair, ...], ...]
    principal: bool
    literal_power: bool
    absolutely_primitive: bool
    status: str
    obstruction: str


@dataclass(frozen=True)
class CrossCheckReport:
    """Δ-prediction vs BFS truth over the full Boolean doctrine lattice."""

    word: str
    doctrines_checked: int
    refused_doctrines: int
    mismatches: tuple[str, ...]
    status: str
    obstruction: str


